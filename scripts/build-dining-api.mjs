import { build } from 'esbuild'
import { readFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
const result=await build({entryPoints:['src/server/diningRequest.ts'],bundle:true,platform:'node',format:'esm',target:'node22',external:['nodemailer','zod'],write:false,legalComments:'none',banner:{js:'// Generated by scripts/build-dining-api.mjs from the shared calculator and server handler. Do not edit by hand.'}})
const output=result.outputFiles[0].text.replace('  handler as default,\n','')+'\nexport default handler;\n'
if(process.argv.includes('--check')){
 assert.equal(await readFile('api/dining-request.ts','utf8'),output,'Regenerate the dining API after changing menu, settings or logic.')
 console.log('Dining API is in sync with the customer calculator.')
}else{
 const {writeFile}=await import('node:fs/promises')
 await writeFile('api/dining-request.ts',output)
 console.log('Generated self-contained dining API with server-side price validation.')
}
